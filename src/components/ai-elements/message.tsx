export type MessageResponseProps = ComponentProps<typeof Streamdown>;

const streamdownPlugins = { cjk, code, math, mermaid };

/** Image component for markdown-embedded images (![alt](/api/files/raw?...)) */
function MarkdownImage(props: React.ImgHTMLAttributes<HTMLImageElement>) {
  const { src, alt, ...rest } = props;
  const [error, setError] = useState<string | null>(null);

  // Cache-bust /api/files/raw URLs so overwritten files (same name) show the new version.
  // The timestamp is captured once on mount via useState initializer — stable across re-renders.
  const [bustSrc] = useState(() => {
    if (!src) return src;
    if (typeof src === 'string' && src.includes('/api/files/raw')) {
      const sep = src.includes('?') ? '&' : '?';
      return `${src}${sep}_t=${Date.now()}`;
    }
    return src;
  });

  const handleError = useCallback(async () => {
    if (!bustSrc) { setError('No image source provided'); return; }
    try {
      const res = await fetch(bustSrc as string, { method: 'HEAD' });
      if (res.status === 403) setError('Access denied — file outside allowed directories');
      else if (res.status === 404) setError('File not found on disk');
      else setError(`Failed to load image (HTTP ${res.status})`);
    } catch {
      setError('Failed to load image');
    }
  }, [bustSrc]);

  if (error) {
    return (
      <span className="block min-w-[120px] max-w-md my-2">
        <span className="block rounded-lg border border-red-500/30 bg-red-500/5 px-3 py-2 text-xs text-red-600 dark:text-red-400">
          <span className="block font-medium">Image failed to render</span>
          {alt && <span className="block mt-0.5 text-muted-foreground">{alt}</span>}
          <span className="block mt-1">{error}</span>
        </span>
      </span>
    );
  }

  return (
    <span className="block my-2">
      <span className="block rounded-lg overflow-hidden border border-border/30 bg-muted/20">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={bustSrc}
          alt={alt || ''}
          className="w-full object-contain"
          onError={handleError}
          {...rest}
        />
        {alt && <span className="block px-2 pb-1 text-xs text-muted-foreground truncate">{alt}</span>}
      </span>
    </span>
  );
}

const streamdownComponents = { img: MarkdownImage };

export const MessageResponse = memo(
  ({ className, ...props }: MessageResponseProps) => (
    <Streamdown
      className={cn(
        "size-full [&>*:first-child]:mt-0 [&>*:last-child]:mb-0",
        className
      )}
      plugins={streamdownPlugins}
      components={streamdownComponents}
      {...props}
    />
  ),
  (prevProps, nextProps) => prevProps.children === nextProps.children
);

MessageResponse.displayName = "MessageResponse";

